const DEFAULT_LANGUAGE = 'en';

document.addEventListener('DOMContentLoaded', () => {
    
    // --- 1. Language Switcher Logic ---
    let currentLang = DEFAULT_LANGUAGE;
    try {
        const savedLang = localStorage.getItem('preferred-lang');
        if (savedLang) currentLang = savedLang;
        else if (navigator.language.startsWith('ar')) currentLang = 'ar';
    } catch (e) {}

    setLanguage(currentLang);

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            setLanguage(e.target.getAttribute('data-lang'));
        });
    });

    function setLanguage(lang) {
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
        });

        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang][key]) {
                if (key === 'coin-text' || key === 'cta-vertical') el.innerHTML = translations[lang][key]; 
                else  el.textContent = translations[lang][key];
            }
        });

        try { localStorage.setItem('preferred-lang', lang); } catch (e) {}

         // تحديث رابط الواتساب بناءً على اللغة
        updateWhatsAppLinks(lang);

         // --- تحديث رابط السيرة الذاتية بناءً على اللغة ---
    const cvBtn = document.querySelector('.cv-download-btn');
    if (cvBtn) {
        if (lang === 'ar') {
            cvBtn.href = 'assets/Suha_Salah-CV-AR.pdf'; // مسار الملف العربي
        } else {
            cvBtn.href = 'assets/Suha_Salah-CV-EN.pdf'; // مسار الملف الإنجليزي
        }
    }
    }

});

    // --- 3. Mobile Menu Toggle ---
    const mobileMenuBtn = document.querySelector('.mobile-menu-btn');
    const navWrapper = document.querySelector('.nav-wrapper');
    const navLinks = document.querySelectorAll('nav a');

    if (mobileMenuBtn && navWrapper) {
        // فتح وإغلاق القائمة
        mobileMenuBtn.addEventListener('click', () => {
            mobileMenuBtn.classList.toggle('active');
            navWrapper.classList.toggle('active');
            
            // تحديث حالة aria-expanded لتحسين إمكانية الوصول
            const isExpanded = mobileMenuBtn.getAttribute('aria-expanded') === 'true';
            mobileMenuBtn.setAttribute('aria-expanded', !isExpanded);
        });

        // إغلاق القائمة تلقائياً عند الضغط على أي رابط
        navLinks.forEach(link => {
            link.addEventListener('click', () => {
                mobileMenuBtn.classList.remove('active');
                navWrapper.classList.remove('active');
                mobileMenuBtn.setAttribute('aria-expanded', 'false');
            });
        });
    }

        // --- 4. Header Scroll Effect ---
    const header = document.querySelector('header');

    window.addEventListener('scroll', () => {
        if (window.scrollY > 50) {
            // إذا نزل المستخدم أكثر من 50 بكسل، أضف الظل
            header.classList.add('scrolled');
        } else {
            // إذا عاد للأعلى، أزل الظل
            header.classList.remove('scrolled');
        }
    });

        // --- 5. Scroll to Top Button Logic ---
    const scrollToTopBtn = document.getElementById('scrollToTopBtn');

    if (scrollToTopBtn) {
        // إظهار/إخفاء الزر بناءً على مسافة التمرير
        window.addEventListener('scroll', () => {
            if (window.scrollY > 400) { // يظهر بعد النزول 400 بكسل
                scrollToTopBtn.classList.add('visible');
            } else {
                scrollToTopBtn.classList.remove('visible');
            }
        });

        // التمرير السلس للأعلى عند الضغط
        scrollToTopBtn.addEventListener('click', () => {
            window.scrollTo({
                top: 0,
                behavior: 'smooth'
            });
        });
    }

        // دالة لتحديث روابط الواتساب
    function updateWhatsAppLinks(lang) {
        const phone = whatsappConfig.phone;
        // تشفير الرسالة لتناسب الروابط (URL Encoding)
        const message = encodeURIComponent(whatsappConfig.messages[lang]);
        const waLink = `https://wa.me/${phone}?text=${message}`;

        // تحديث جميع الأزرار التي تحمل كلاس whatsapp-btn
        const waButtons = document.querySelectorAll('.whatsapp-btn');
        waButtons.forEach(btn => {
            btn.setAttribute('href', waLink);
        });
    }

        // ==========================================
    // 7. Service Cards to WhatsApp (Smart Link)
    // ==========================================
    const serviceCards = document.querySelectorAll('.service-card');
    
    if (serviceCards.length > 0) {
        serviceCards.forEach(card => {
            card.style.cursor = 'pointer'; // تغيير شكل الماوس ليدل على أنه قابل للضغط
            
            card.addEventListener('click', (e) => {
                e.preventDefault(); // منع أي سلوك افتراضي للرابط
                
                // الحصول على اسم الخدمة المكتوب في البطاقة (عربي أو إنجليزي حسب اللغة الحالية)
                const titleElement = card.querySelector('.card-title');
                const serviceName = titleElement ? titleElement.innerText : '';
                
                const lang = document.documentElement.lang || 'en';
                let message = '';
                
                // تجهيز الرسالة بناءً على اللغة
                if (lang === 'ar') {
                    message = `مرحباً سها، أنا مهتم بخدمة: ${serviceName}. هل يمكننا التحدث حول مشروعي؟`;
                } else {
                    message = `Hello Suha, I'm interested in your service: ${serviceName}. Can we talk about my project?`;
                }
                
                // فتح الواتساب
                const phone = whatsappConfig.phone;
                const waLink = `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
                window.open(waLink, '_blank');
            });
        });
    }